package com.github.lechandonga.artifacttrustgatejava.model;

/**
 * 准入结论。细分拒绝原因，避免所有失败都归为笼统错误。
 */
public enum DecisionCode {
    ALLOW,
    REJECT_UNKNOWN_ARTIFACT,
    REJECT_ATTESTATION_MISSING,
    REJECT_SIGNATURE_MISSING,
    REJECT_KEY_UNKNOWN,
    REJECT_CONTENT_DIGEST_MISMATCH,
    REJECT_SIGNATURE_INVALID,
    REJECT_ATTESTATION_EXPIRED,
    REJECT_KEY_REVOKED,
    REJECT_POLICY_DENY,
    REJECT_POLICY_VERSION_UNKNOWN,
    REJECT_KEYBOOK_VERSION_UNKNOWN,
    REJECT_BAD_REQUEST
}
